const BOARDS: readonly Board[] = ['meal', 'career', 'hobby', 'show'];
const MINUTE_MS = 60_000;

// The instant `day` days after the frame's day at `clock` in Korea.
function at(day: string, clock: string): string {
  const [hour = 0, minute = 0] = clock.split(':').map(Number);
  const midnight = new Date(frameTime('00:00')).getTime();
  return new Date(midnight + Number(day) * DAY_MS + (hour * 60 + minute) * MINUTE_MS).toISOString();
}

function entryOf(row: string, index: number): RecruitingQuest {
  const [board, title, description, day, clock, place, holders, capacity, leader, department, posted, postedClock] = row
    .split('|')
    .map(String);
  const id = `post-${String(index)}`;
  return {
    id,
    title,
    globalEvent: index === 2 ? { id: 'e-jazz', title: '재즈 정기공연' } : null,
    leader: { id: `${id}-leader`, name: leader, department },
    holderCount: Number(holders),
    capacity: Number(capacity),
    joinPolicy: index % 3 === 1 ? 'approval' : 'open',
    board: BOARDS.find((one) => one === board) ?? 'hobby',
    description,
    createdAt: at(posted, postedClock),
    nextSubQuest: {
      id: `${id}-1`,
      title,
      startsAt: at(day, clock),
      endsAt: null,
      place: { placeId: null, label: place, ...CAMPUS },
    },
  };
}

export const RECRUITING_QUESTS: RecruitingQuest[] = ROWS.map((row, index) => entryOf(row, index)).toSorted(
  (one, other) => other.createdAt.localeCompare(one.createdAt),
);
